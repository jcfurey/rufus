"""Extract supported Linux live ISOs to FAT32, with native x86/ARM64 GRUB."""

from dataclasses import dataclass
import hashlib
import os
from pathlib import Path, PurePosixPath
import re
import shlex
import shutil
import tempfile

from .backup import new_output
from .boot import MIB, copy_sparse
from .core import (FAT_MAX_FILE, RufusError, check_cancel, checksums, checksum, emit, expected_sha256,
                   image_filesystems, run_tool, source_file, validate_fat_tree)
from . import grub
from .layout import Partition, write_layout
from .live import MANIFESTS, iso_command, tool_text, validate_persistence
from .windows import case_path


@dataclass(frozen=True)
class LiveEntry:
    title: str
    kernel: str
    arguments: tuple
    initrds: tuple
    kind: str


def brace_delta(line):
    line = re.sub(r"\$\{[^}]*\}", "variable", line)
    quote, escaped, count = "", False, 0
    for char in line:
        if escaped:
            escaped = False
        elif char == "\\" and quote != "'":
            escaped = True
        elif char == quote:
            quote = ""
        elif quote:
            continue
        elif char in ("'", '"'):
            quote = char
        elif char == "#":
            break
        elif char == "{":
            count += 1
        elif char == "}":
            count -= 1
    return count


def grub_quote(text):
    if any(ord(char) < 32 for char in text):
        raise RufusError("Unsupported control character in Linux boot configuration.")
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'


def tree_file(root, path):
    if not path.startswith("/") or ".." in PurePosixPath(path).parts or "$" in path:
        raise RufusError(f"Unsupported Linux boot path: {path}")
    result = root / path.lstrip("/")
    if not result.is_file() or result.is_symlink() or not result.resolve().is_relative_to(root.resolve()):
        raise RufusError(f"Linux boot file is missing or unsafe: {path}")
    return result


def menu_entries(root, text):
    entries, title, body, depth = [], None, [], 0
    for line in re.sub(r"\\\r?\n", " ", text).splitlines():
        if title is None:
            if not re.match(r"^\s*menuentry\s", line) or not line.rstrip().endswith("{"):
                continue
            words = shlex.split(line, comments=True)
            if len(words) < 3:
                continue
            title, body, depth = words[1], [], brace_delta(line)
            continue
        depth += brace_delta(line)
        if depth > 0:
            body.append(line)
            continue
        commands = [shlex.split(value, comments=True) for value in body]
        kernels = [c for c in commands if c and c[0] in ("linux", "linuxefi", "linux16")]
        initrds = [c for c in commands if c and c[0] in ("initrd", "initrdefi", "initrd16")]
        if len(kernels) == 1 and len(kernels[0]) >= 2 and len(initrds) == 1 and len(initrds[0]) >= 2:
            kernel, arguments = kernels[0][1], tuple(kernels[0][2:])
            kind = "debian" if "boot=live" in arguments else (
                "casper" if "boot=casper" in arguments or kernel.startswith("/casper/") else None)
            if kind:
                tree_file(root, kernel)
                for path in initrds[0][1:]:
                    tree_file(root, path)
                entries.append(LiveEntry(title, kernel, arguments, tuple(initrds[0][1:]), kind))
        title = None
    if not entries or len(entries) > 64 or len({e.kind for e in entries}) != 1:
        raise RufusError("FAT32 extraction requires conventional GRUB Casper or Debian live menu entries.")
    return entries


def boot_config(entries, persistence):
    lines = ["# Generated by Rufus for Linux", "set default=0", "set timeout=5", ""]
    for entry in entries:
        arguments = []
        for word in entry.arguments:
            if word.startswith(("iso-scan/filename=", "findiso=", "fromiso=")) or word == "$vt_handoff":
                continue
            if "$" in word or ";" in word:
                raise RufusError("Linux menu uses boot variables or commands that cannot be extracted safely.")
            if word.startswith(("persistent-path=", "persistence-")):
                raise RufusError("Custom persistence-store options are not supported in FAT32 extraction mode.")
            if word not in ("persistent", "persistence"):
                arguments.append(word)
        if entry.kind == "casper" and "boot=casper" not in arguments:
            arguments.insert(0, "boot=casper")
        disabled = "nopersistent" if entry.kind == "casper" else "nopersistence"
        option = "persistent" if entry.kind == "casper" else "persistence"
        if disabled not in arguments and "integrity-check" not in arguments:
            before = next((i for i, word in enumerate(arguments) if word in ("--", "---")), len(arguments))
            arguments.insert(before, option if persistence else disabled)
        lines += [f"menuentry {grub_quote(entry.title)} {{",
                  "    linux " + " ".join(grub_quote(word) for word in (entry.kernel, *arguments)),
                  "    initrd " + " ".join(grub_quote(path) for path in entry.initrds), "}", ""]
    return "\n".join(lines)


def partitions(size, persistence_size, firmware):
    if size % 512 or size < persistence_size + 66 * MIB:
        raise RufusError("Extracted image needs at least 64 MiB for FAT32 plus persistence and partition metadata.")
    table = "gpt" if firmware == "uefi" else "dos"
    end = ((size // 512 - (34 if table == "gpt" else 0)) // 2048) * 2048
    main_end = end - persistence_size // 512
    parts = [Partition(2048, main_end - 2048, "esp" if firmware != "bios" else "basic",
                       0xef if firmware != "bios" else 0x0c, "Linux live", firmware != "uefi")]
    if parts[0].sectors > 0xffffffff or table == "dos" and size > 2**41:
        raise RufusError("Selected disk exceeds the FAT32/MBR image size limits.")
    if persistence_size:
        parts.append(Partition(main_end, persistence_size // 512, "linux", 0x83, "Persistence"))
    return table, parts


def refresh_manifests(root, cancel=None, progress=None):
    manifests = [(root / path.lstrip("/"), algorithm) for path, algorithm in MANIFESTS.items()
                 if (root / path.lstrip("/")).is_file()]
    if not manifests:
        return
    excluded = {path for path, _ in manifests}
    files = [p for p, _, _ in validate_fat_tree(root)[0] if p not in excluded]
    algorithms = tuple(sorted({algorithm for _, algorithm in manifests}))
    rows = {algorithm: [] for algorithm in algorithms}
    for index, path in enumerate(sorted(files)):
        emit(progress, "Updating live media checksums", index, len(files))
        values = checksums(path, algorithms, cancel) if path.stat().st_size else {
            algorithm: hashlib.new(algorithm).hexdigest() for algorithm in algorithms}
        for algorithm, digest in values.items():
            rows[algorithm].append(f"{digest}  ./{path.relative_to(root).as_posix()}\n")
    for path, algorithm in manifests:
        path.write_text("".join(rows[algorithm]), encoding="utf-8")


def create_extracted_image(source, output, size=None, persistence_size=0, casper_label="writable",
                           architecture="auto", firmware=None, expected="", cancel=None, progress=None):
    if persistence_size:
        validate_persistence(persistence_size, casper_label)
    elif persistence_size != 0:
        raise RufusError("Persistence size must be zero or at least 64 MiB.")
    expected = expected_sha256(expected)
    if os.path.lexists(output):
        raise RufusError("Image destination already exists. Select a new filename.")
    for tool in ("xorriso", "mkfs.vfat", "mcopy", "fsck.fat", "grub-mkimage") + (
            ("mkfs.ext4", "e2fsck") if persistence_size else ()):
        if not shutil.which(tool):
            raise RufusError(f"Linux FAT32 extraction requires {tool}.")
    source = Path(source).resolve()
    with source_file(source) as stream:
        before = os.fstat(stream.fileno())
        if not image_filesystems(stream.read(65536))[0]:
            raise RufusError("Linux extraction requires an uncompressed ISO9660 live image.")
    source_hash = checksum(source, cancel, progress)
    if expected and source_hash != expected:
        raise RufusError("Linux ISO SHA-256 does not match the expected checksum.")
    if tool_text(iso_command(source, "-find", "/", "-type", "f", "-name", "*.nvidia.squashfs",
                             "-exec", "echo", "--"), cancel).strip():
        raise RufusError("Use Jetson installer mode to preserve NVIDIA's installer and firmware support unchanged.")
    with tempfile.TemporaryDirectory(prefix="rufus-linux-extract-") as directory:
        work = Path(directory)
        root = work / "files"
        root.mkdir()
        emit(progress, "Extracting Linux live ISO")
        run_tool(iso_command(source, "-osirrox", "on", "-extract", "/", str(root)), cancel)
        files, names = validate_fat_tree(root)
        primary = names.get("boot/grub/grub.cfg") or names.get("efi/boot/grub.cfg")
        if not primary or primary.stat().st_size > MIB:
            raise RufusError("ISO needs a supported GRUB live configuration.")
        if "boot/rufus" in names:
            raise RufusError("ISO already contains Rufus's generated boot directory. Select the original ISO.")
        entries = menu_entries(root, primary.read_text(encoding="utf-8"))
        detected = {grub.kernel_architecture(tree_file(root, entry.kernel)) for entry in entries}
        if len(detected) != 1:
            raise RufusError("ISO contains mixed Linux kernel architectures.")
        detected = detected.pop()
        if architecture != "auto" and architecture != detected:
            raise RufusError(f"Selected architecture {architecture} does not match the ISO's {detected} kernel.")
        architecture = detected
        firmware, targets = grub.target_modules(architecture, firmware)
        if any(amount > FAT_MAX_FILE for _, _, amount in files):
            raise RufusError("ISO has a file larger than FAT32 permits. Use hybrid mode or DD mode.")
        serial = os.urandom(4).hex().upper()
        filesystem_uuid = serial[:4] + "-" + serial[4:]
        emit(progress, "Building matching GRUB bootloaders")
        bios_core, versions = grub.build_loaders(root, work, filesystem_uuid, architecture, targets, cancel)
        (case_path(root, grub.PREFIX.lstrip("/")) / "grub.cfg").write_text(boot_config(entries, persistence_size), encoding="utf-8")
        refresh_manifests(root, cancel, progress)
        files, _ = validate_fat_tree(root)
        content = sum(amount for _, _, amount in files)
        minimum = content + len(files) * 32768 + 32 * MIB
        if size is None:
            size = max(128 * MIB, ((content * 11 // 10 + len(files) * 32768 + 128 * MIB + MIB - 1) // MIB) * MIB)
            size += persistence_size + 2 * MIB
        table, parts = partitions(size, persistence_size, firmware)
        if parts[0].sectors * 512 < minimum:
            raise RufusError("Live files and persistence will not fit in the requested image size.")
        volume = work / "fat32.img"
        with volume.open("xb") as disk:
            disk.truncate(parts[0].sectors * 512)
        run_tool(["mkfs.vfat", "-F", "32", "-i", serial, "-h", "2048", "-n", "RUFUS_LIVE", str(volume)], cancel)
        children = sorted(root.iterdir())
        for index, child in enumerate(children):
            emit(progress, "Copying Linux live files to FAT32", index, len(children))
            run_tool(["mcopy", "-s", "-i", str(volume), str(child), "::/"], cancel)
        run_tool(["fsck.fat", "-n", str(volume)], cancel)
        kind = entries[0].kind
        label = (casper_label if kind == "casper" else "persistence") if persistence_size else None
        persistence = work / "persistence.ext4"
        if persistence_size:
            seed = work / "persistence-root"
            seed.mkdir()
            if kind == "debian":
                (seed / "persistence.conf").write_text("/ union\n", encoding="utf-8")
            with persistence.open("xb") as disk:
                disk.truncate(persistence_size)
            emit(progress, "Creating ext4 persistence volume")
            run_tool(["mkfs.ext4", "-q", "-F", "-L", label, "-m", "0", "-O", "^orphan_file",
                      "-E", "lazy_itable_init=0,lazy_journal_init=0", "-d", str(seed), str(persistence)], cancel)
            run_tool(["e2fsck", "-fn", str(persistence)], cancel)
        after = source.stat()
        if (before.st_dev, before.st_ino, before.st_size, before.st_mtime_ns, before.st_ctime_ns) != (
                after.st_dev, after.st_ino, after.st_size, after.st_mtime_ns, after.st_ctime_ns):
            raise RufusError("Linux ISO changed during extraction.")
        with new_output(output) as target, volume.open("rb") as payload:
            os.ftruncate(target, size)
            write_layout(target, size, parts, table)
            if bios_core:
                grub.embed_bios(target, targets["i386-pc"], bios_core)
            copy_sparse(payload.fileno(), target, parts[0].start * 512, parts[0].sectors * 512, cancel, progress)
            if persistence_size:
                with persistence.open("rb") as store:
                    copy_sparse(store.fileno(), target, parts[1].start * 512, persistence_size, cancel, progress)
            os.fsync(target)
            digest = checksum(output, cancel, progress)
            check_cancel(cancel)
            emit(progress, "Complete", size, size)
    return {"sha256": digest, "source_sha256": source_hash, "size": size, "mode": "extract",
            "architecture": architecture, "firmware": firmware, "filesystem": "vfat", "table": table,
            "persistence_size": persistence_size, "persistence_label": label, "kind": kind,
            "grub_versions": versions}
